/// Design system token values for spacing and layout grids (in dp).
class AppSpacing {
  const AppSpacing._();

  /// Zero spacing.
  static const double none = 0;

  /// Extra-small spacing (4dp).
  static const double xs = 4;

  /// Small spacing (8dp).
  static const double sm = 8;

  /// Medium spacing (16dp).
  static const double md = 16;

  /// Large spacing (24dp).
  static const double lg = 24;

  /// Extra-large spacing (32dp).
  static const double xl = 32;

  /// Double extra-large spacing (48dp).
  static const double xxl = 48;

  /// Standard column spacing gutter (16dp).
  static const double gutter = 16;

  /// Layout margin for mobile displays (16dp).
  static const double marginMobile = 16;

  /// Layout margin for tablet displays (24dp).
  static const double marginTablet = 24;

  /// Layout margin for desktop displays (32dp).
  static const double marginDesktop = 32;
}
