/// Design system token values for corner radius (in dp).
class AppRadius {
  const AppRadius._();

  /// Extra small radius (4dp).
  static const double xs = 4;

  /// Small radius (8dp).
  static const double sm = 8;

  /// Medium radius (8dp).
  static const double md = 8;

  /// Large radius (16dp).
  static const double lg = 16;

  /// Increased large radius (20dp).
  static const double lgIncreased = 20;

  /// Extra large radius (28dp).
  static const double xl = 28;

  /// Increased extra large radius (32dp).
  static const double xlIncreased = 32;

  /// Double extra large radius (48dp).
  static const double xxl = 48;

  /// Maximum radius for fully circular shapes.
  static const double full = 9999;
}
