/// Radius tokens for the Core Logic Visual Language.
class CoreRadius {
  CoreRadius._();

  /// Extra small radius (2.0) - used for tooltips and checkboxes.
  static const double xs = 2;

  /// Small radius (4.0) - standard for text fields and chips.
  static const double sm = 4;

  /// Base/Medium radius (8.0) - standard for cards and small dialogs.
  static const double base = 8;

  /// Medium radius (12.0) - used for medium containers.
  static const double md = 12;

  /// Large radius (16.0) - used for primary container elements.
  static const double lg = 16;

  /// Extra large radius (24.0) - used for bottom sheets and large modal surfaces.
  static const double xl = 24;

  /// Full radius (9999.0) - reserved for buttons and status indicators.
  static const double full = 9999;
}
